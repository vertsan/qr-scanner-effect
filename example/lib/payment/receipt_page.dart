// The receipt the host shows after *it* has confirmed the payment.
//
// The package drew the overlay; the host's gate authorised the payment; this
// screen is the host's own record of it. Nothing here comes from `qr_scan_fx`.

import 'package:flutter/material.dart';
import 'package:share_plus/share_plus.dart';

import 'khqr.dart';
import 'payment_models.dart';
import 'receipt_saver.dart';

/// A shareable, saveable receipt for one confirmed payment.
class ReceiptPage extends StatelessWidget {
  /// Creates a receipt page for [receipt].
  const ReceiptPage({super.key, required this.receipt});

  /// The confirmed payment.
  final PaymentReceipt receipt;

  String get _shareText {
    final StringBuffer buffer = StringBuffer()
      ..writeln('Payment receipt')
      ..writeln('----------------------------')
      ..writeln('Transaction: ${receipt.id}')
      ..writeln('Date: ${formatTimestamp(receipt.createdAt)}')
      ..writeln('Payee: ${receipt.payee}')
      ..writeln('Paid from: $_accountLabel')
      ..writeln('Amount: ${formatMoney(receipt.amount, receipt.currency)}')
      ..writeln('≈ ${formatMoney(receipt.otherAmount, receipt.otherCurrency)}')
      ..writeln()
      ..writeln('Generated by the qr_scan_fx example app.');
    return buffer.toString();
  }

  String get _accountLabel {
    final String? masked = receipt.account.maskedNumber;
    return masked == null ? receipt.account.label : '${receipt.account.label} $masked';
  }

  Future<void> _share() async {
    await SharePlus.instance.share(
      ShareParams(
        text: _shareText,
        subject: 'Payment receipt ${receipt.id}',
      ),
    );
  }

  Future<void> _save(BuildContext context) async {
    final String? path = await saveReceiptFile(
      fileName: 'receipt_${receipt.id}.txt',
      contents: _shareText,
    );
    if (!context.mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(
          path == null
              ? 'Saving a file is not supported on this platform — use Share instead.'
              : 'Saved receipt to $path',
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final ThemeData theme = Theme.of(context);
    return Scaffold(
      appBar: AppBar(
        title: const Text('Receipt'),
        automaticallyImplyLeading: false,
      ),
      body: SafeArea(
        child: ListView(
          padding: const EdgeInsets.fromLTRB(20, 12, 20, 24),
          children: <Widget>[
            Center(
              child: Icon(
                Icons.check_circle,
                size: 64,
                color: theme.colorScheme.primary,
              ),
            ),
            const SizedBox(height: 12),
            Center(
              child: Text(
                'Payment successful',
                style: theme.textTheme.titleLarge,
              ),
            ),
            const SizedBox(height: 4),
            Center(
              child: Text(
                formatMoney(receipt.amount, receipt.currency),
                style: theme.textTheme.headlineMedium?.copyWith(
                  fontWeight: FontWeight.w700,
                ),
              ),
            ),
            Center(
              child: Text(
                '≈ ${formatMoney(receipt.otherAmount, receipt.otherCurrency)}',
                style: theme.textTheme.bodyMedium?.copyWith(
                  color: theme.colorScheme.onSurfaceVariant,
                ),
              ),
            ),
            const SizedBox(height: 28),
            Card(
              child: Padding(
                padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
                child: Column(
                  children: <Widget>[
                    _ReceiptRow(label: 'Payee', value: receipt.payee),
                    _ReceiptRow(label: 'Paid from', value: _accountLabel),
                    _ReceiptRow(label: 'Transaction', value: receipt.id),
                    _ReceiptRow(
                      label: 'Date',
                      value: formatTimestamp(receipt.createdAt),
                    ),
                    _ReceiptRow(
                      label: 'Status',
                      value: 'Confirmed',
                      valueColor: theme.colorScheme.primary,
                    ),
                  ],
                ),
              ),
            ),
            const SizedBox(height: 28),
            Row(
              children: <Widget>[
                Expanded(
                  child: OutlinedButton.icon(
                    onPressed: _share,
                    icon: const Icon(Icons.ios_share),
                    label: const Text('Share'),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: OutlinedButton.icon(
                    onPressed: () => _save(context),
                    icon: const Icon(Icons.save_alt),
                    label: const Text('Save'),
                  ),
                ),
              ],
            ),
            const SizedBox(height: 12),
            SizedBox(
              width: double.infinity,
              child: FilledButton(
                onPressed: () => Navigator.of(context).pop(),
                child: const Text('Done'),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

class _ReceiptRow extends StatelessWidget {
  const _ReceiptRow({
    required this.label,
    required this.value,
    this.valueColor,
  });

  final String label;
  final String value;
  final Color? valueColor;

  @override
  Widget build(BuildContext context) {
    final ThemeData theme = Theme.of(context);
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 12),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: <Widget>[
          SizedBox(
            width: 104,
            child: Text(
              label,
              style: theme.textTheme.bodyMedium?.copyWith(
                color: theme.colorScheme.onSurfaceVariant,
              ),
            ),
          ),
          Expanded(
            child: Text(
              value,
              textAlign: TextAlign.right,
              style: theme.textTheme.bodyMedium?.copyWith(
                color: valueColor,
                fontWeight: FontWeight.w600,
              ),
            ),
          ),
        ],
      ),
    );
  }
}
