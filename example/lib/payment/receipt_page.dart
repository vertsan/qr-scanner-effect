// The receipt the host shows after *it* has confirmed the payment.
//
// The package drew the overlay; the host's gate authorised the payment; this
// screen is the host's own record of it. Nothing here comes from `qr_scan_fx`.

import 'dart:math' as math;

import 'package:flutter/material.dart';
import 'package:share_plus/share_plus.dart';

import 'khqr.dart';
import 'payment_models.dart';
import 'receipt_saver.dart';
import '../theme.dart';

/// A shareable, saveable receipt for one confirmed payment.
class ReceiptPage extends StatelessWidget {
  /// Creates a receipt page for [receipt].
  const ReceiptPage({super.key, required this.receipt});

  /// The confirmed payment.
  final PaymentReceipt receipt;

  String get _shareText {
    final StringBuffer buffer = StringBuffer()
      ..writeln('Payment receipt')
      ..writeln('----------------------------')
      ..writeln('Transaction: ${receipt.id}')
      ..writeln('Date: ${formatTimestamp(receipt.createdAt)}')
      ..writeln('Payee: ${receipt.payee}')
      ..writeln('Paid from: $_accountLabel')
      ..writeln('Amount: ${formatMoney(receipt.amount, receipt.currency)}')
      ..writeln('≈ ${formatMoney(receipt.otherAmount, receipt.otherCurrency)}')
      ..writeln()
      ..writeln('Generated by the qr_scan_fx example app.');
    return buffer.toString();
  }

  String get _accountLabel {
    final String? masked = receipt.account.maskedNumber;
    return masked == null
        ? receipt.account.label
        : '${receipt.account.label} $masked';
  }

  Future<void> _share() async {
    await SharePlus.instance.share(
      ShareParams(
        text: _shareText,
        subject: 'Payment receipt ${receipt.id}',
      ),
    );
  }

  Future<void> _save(BuildContext context) async {
    final String? path = await saveReceiptFile(
      fileName: 'receipt_${receipt.id}.txt',
      contents: _shareText,
    );
    if (!context.mounted) return;
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Text(
          path == null
              ? 'Saving a file is not supported on this platform — use Share instead.'
              : 'Saved receipt to $path',
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final ThemeData theme = Theme.of(context);
    final bool reduceMotion = MediaQuery.disableAnimationsOf(context);

    return Scaffold(
      appBar: AppBar(
        title: const Text('Receipt'),
        automaticallyImplyLeading: false,
      ),
      body: ListView(
        padding: const EdgeInsets.fromLTRB(20, 8, 20, 24),
        children: <Widget>[
          _SuccessHero(reduceMotion: reduceMotion),
          const SizedBox(height: 12),
          Text(
            'Payment successful',
            textAlign: TextAlign.center,
            style: theme.textTheme.titleLarge?.copyWith(
              fontWeight: FontWeight.w700,
            ),
          ),
          const SizedBox(height: 4),
          Text(
            formatMoney(receipt.amount, receipt.currency),
            textAlign: TextAlign.center,
            style: theme.textTheme.headlineMedium?.copyWith(
              fontWeight: FontWeight.w700,
            ),
          ),
          Text(
            '≈ ${formatMoney(receipt.otherAmount, receipt.otherCurrency)}',
            textAlign: TextAlign.center,
            style: theme.textTheme.bodyMedium?.copyWith(
              color: AppTheme.onSurfaceVariant,
            ),
          ),
          const SizedBox(height: 28),
          Container(
            padding: const EdgeInsets.fromLTRB(18, 18, 18, 10),
            decoration: BoxDecoration(
              color: AppTheme.surface,
              border:
                  Border.all(color: AppTheme.outline.withValues(alpha: 0.7)),
              borderRadius: BorderRadius.circular(18),
            ),
            child: Column(
              children: <Widget>[
                _ReceiptRow(label: 'Payee', value: receipt.payee),
                _ReceiptRow(label: 'Paid from', value: _accountLabel),
                _ReceiptRow(
                  label: 'Transaction',
                  value: receipt.id,
                  tabular: true,
                ),
                _ReceiptRow(
                  label: 'Date',
                  value: formatTimestamp(receipt.createdAt),
                  tabular: true,
                ),
                const _DashedDivider(),
                _ReceiptRow(
                  label: 'Status',
                  value: 'Confirmed',
                  valueColor: AppTheme.positive,
                ),
              ],
            ),
          ),
          const SizedBox(height: 28),
          Row(
            children: <Widget>[
              Expanded(
                child: OutlinedButton.icon(
                  onPressed: _share,
                  icon: const Icon(Icons.ios_share, size: 18),
                  label: const Text('Share'),
                ),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: OutlinedButton.icon(
                  onPressed: () => _save(context),
                  icon: const Icon(Icons.save_alt, size: 18),
                  label: const Text('Save'),
                ),
              ),
            ],
          ),
          const SizedBox(height: 12),
          FilledButton(
            onPressed: () => Navigator.of(context).pop(),
            child: const Text('Done'),
          ),
        ],
      ),
    );
  }
}

/// A gentle check that scales in — skipped entirely when the system asks for
/// reduced motion.
class _SuccessHero extends StatelessWidget {
  const _SuccessHero({required this.reduceMotion});

  final bool reduceMotion;

  @override
  Widget build(BuildContext context) {
    const Widget icon = Icon(Icons.check, size: 40, color: AppTheme.onAccent);

    return Center(
      child: TweenAnimationBuilder<double>(
        tween: Tween<double>(begin: reduceMotion ? 1 : 0.55, end: 1),
        duration:
            reduceMotion ? Duration.zero : const Duration(milliseconds: 460),
        curve: Curves.easeOutBack,
        builder: (BuildContext context, double scale, Widget? child) =>
            Transform.scale(scale: scale, child: child),
        child: Container(
          width: 76,
          height: 76,
          decoration: BoxDecoration(
            color: AppTheme.accent,
            shape: BoxShape.circle,
          ),
          child: icon,
        ),
      ),
    );
  }
}

class _ReceiptRow extends StatelessWidget {
  const _ReceiptRow({
    required this.label,
    required this.value,
    this.valueColor,
    this.tabular = false,
  });

  final String label;
  final String value;
  final Color? valueColor;
  final bool tabular;

  @override
  Widget build(BuildContext context) {
    final ThemeData theme = Theme.of(context);
    return Padding(
      padding: const EdgeInsets.symmetric(vertical: 13),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: <Widget>[
          SizedBox(
            width: 104,
            child: Text(
              label,
              style: theme.textTheme.bodyMedium?.copyWith(
                color: AppTheme.onSurfaceVariant,
              ),
            ),
          ),
          Expanded(
            child: Text(
              value,
              textAlign: TextAlign.right,
              style: theme.textTheme.bodyMedium?.copyWith(
                color: valueColor,
                fontWeight: FontWeight.w600,
                fontFeatures: tabular
                    ? const <FontFeature>[FontFeature.tabularFigures()]
                    : null,
              ),
            ),
          ),
        ],
      ),
    );
  }
}

/// A dotted rule, so the card reads like a printed ticket.
class _DashedDivider extends StatelessWidget {
  const _DashedDivider();

  @override
  Widget build(BuildContext context) {
    return SizedBox(
      height: 1,
      width: double.infinity,
      child: CustomPaint(
        painter: _DashPainter(
          AppTheme.outline.withValues(alpha: 0.9),
        ),
      ),
    );
  }
}

class _DashPainter extends CustomPainter {
  const _DashPainter(this.color);

  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final Paint paint = Paint()
      ..color = color
      ..strokeWidth = 1;
    const double dashWidth = 6;
    const double gap = 5;
    double x = 0;
    while (x < size.width) {
      final double end = math.min(x + dashWidth, size.width);
      canvas.drawLine(Offset(x, 0), Offset(end, 0), paint);
      x += dashWidth + gap;
    }
  }

  @override
  bool shouldRepaint(_DashPainter oldDelegate) => oldDelegate.color != color;
}
